// Basic Functions in JavaScript

// Function without parameters
function print() 
{
    console.log('Hello World');
}

// Function call
print();


// Function with parameters and return value

function sum(a, b) 
{
    return a + b;
}

const s = sum(4555, 1);
console.log("Sum:", s);




function sub(x, y) {
    console.log("Subtract:", x - y);
}

// Function call
sub(12, 78);
